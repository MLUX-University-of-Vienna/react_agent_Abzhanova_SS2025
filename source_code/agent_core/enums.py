from enum import Enum

class QueryStatus(str, Enum):
    PLANNED = "PLANNED"
    RUNNING = "RUNNING"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
    ANSWERED = "ANSWERED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"

class SubqueryStatus(str, Enum):
    PLANNED = "PLANNED"
    RUNNING = "RUNNING"
    ANSWERED = "ANSWERED"
    FAILED = "FAILED"
    SKIPPED = "SKIPPED"

class ExecutionMode(str, Enum):
    SELF_ANSWER = "SELF_ANSWER"
    NEEDS_TOOLS = "NEEDS_TOOLS"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
